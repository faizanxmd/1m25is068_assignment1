import type { ResearchBrief } from '../types';

export function briefToPlainText(brief: ResearchBrief): string {
  const lines: string[] = [
    `=====================================================================`,
    `RESEARCH PAPER BRIEF: ${brief.topic}`,
    `Generated by Research Paper Agent (Gemini AI)`,
    `Date: ${brief.created_at ? new Date(brief.created_at).toLocaleString() : new Date().toLocaleString()}`,
    `=====================================================================`,
    ``,
    `1. REFINED RESEARCH QUESTION:`,
    `   ${brief.research_question}`,
    ``,
    `2. KEY CONCEPTS & VARIABLES:`,
    ...brief.key_concepts.map((c) => `   - ${c}`),
    ``,
    `3. LITERATURE REVIEW THEMES & SEARCH QUERIES:`,
    ...brief.literature_themes.flatMap((item, idx) => [
      `   Theme ${idx + 1}: ${item.theme}`,
      ...item.search_queries.map((q) => `     * Search Query: "${q}"`),
      ``,
    ]),
    `4. PROPOSED METHODOLOGY:`,
    `   ${brief.methodology}`,
    ``,
    `5. DRAFT ABSTRACT:`,
    `   ${brief.draft_abstract}`,
    ``,
    `6. LIMITATIONS & ETHICAL CONSIDERATIONS:`,
    ...brief.limitations.map((l) => `   - ${l}`),
    ``,
    `7. CITATION VERIFICATION NOTE:`,
    `   ${brief.verify_note}`,
    ``,
    `8. AGENT REASONING LOG:`,
    `   ${brief.reasoning}`,
    `=====================================================================`,
  ];

  return lines.join('\n');
}

export function briefToMarkdown(brief: ResearchBrief): string {
  return `# Research Paper Brief: ${brief.topic}

*Generated on ${brief.created_at ? new Date(brief.created_at).toLocaleDateString() : 'today'} by Research Paper Agent*

---

## 🎯 Refined Research Question
> **${brief.research_question}**

---

## 🔑 Key Concepts & Variables
${brief.key_concepts.map((c) => `- \`${c}\``).join('\n')}

---

## 📚 Literature Review Themes & Search Queries
${brief.literature_themes
  .map(
    (item, idx) => `### ${idx + 1}. ${item.theme}
${item.search_queries
  .map(
    (q) =>
      `- **"${q}"**  \n  [Search Google Scholar](https://scholar.google.com/scholar?q=${encodeURIComponent(
        q
      )}) · [Search arXiv](https://arxiv.org/search/?query=${encodeURIComponent(
        q
      )}&searchtype=all)`
  )
  .join('\n')}`
  )
  .join('\n\n')}

---

## 🔬 Proposed Methodology
${brief.methodology}

---

## 📝 Draft Abstract
${brief.draft_abstract}

---

## ⚠️ Limitations & Open Questions
${brief.limitations.map((l) => `- ${l}`).join('\n')}

---

## 🛡️ Citation Integrity Note
> ${brief.verify_note}

---

## 🧠 Agent Reasoning
${brief.reasoning}
`;
}

export function downloadFile(content: string, filename: string, type: string) {
  const blob = new Blob([content], { type });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
